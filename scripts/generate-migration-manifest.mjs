import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const migrationsDirectory = resolve(root, 'packages/database/migrations');
const outputPath = resolve(root, 'packages/database/src/migration-manifest.ts');
const jsonOutputPath = resolve(root, 'packages/database/src/generated/migration-manifest.json');
const checkOnly = process.argv.includes('--check');

const files = (await readdir(migrationsDirectory))
  .filter((name) => /^\d{4}_[a-z0-9_]+\.sql$/.test(name))
  .sort();
if (files.length === 0) throw new Error('No database migrations were found.');
for (const [index, file] of files.entries()) {
  const expectedPrefix = String(index + 1).padStart(4, '0');
  if (!file.startsWith(`${expectedPrefix}_`)) {
    throw new Error(`Migration sequence is not contiguous at ${file}; expected prefix ${expectedPrefix}.`);
  }
}
const entries = [];
for (const version of files) {
  const sql = await readFile(resolve(migrationsDirectory, version), 'utf8');
  entries.push({ version, checksum: createHash('sha256').update(sql).digest('hex') });
}
const jsonContent = `${JSON.stringify({ schemaVersion: '1.0', migrations: entries }, null, 2)}\n`;
const content = `// Generated by scripts/generate-migration-manifest.mjs. Do not edit by hand.\n` +
  `export const MIGRATION_MANIFEST = ${JSON.stringify(entries, null, 2)} as const;\n\n` +
  `export type MigrationIdentity = (typeof MIGRATION_MANIFEST)[number];\n` +
  `export const EXPECTED_SCHEMA_MIGRATIONS = MIGRATION_MANIFEST.length;\n`;
if (checkOnly) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '');
  const existingJson = await readFile(jsonOutputPath, 'utf8').catch(() => '');
  if (existing !== content || existingJson !== jsonContent) throw new Error('Generated migration manifest is stale. Run pnpm generate:manifests.');
  process.stdout.write(`migration manifest verified (${entries.length} entries)\n`);
} else {
  await writeFile(outputPath, content);
  await writeFile(jsonOutputPath, jsonContent);
  process.stdout.write(`wrote ${outputPath} (${entries.length} entries)\n`);
}
